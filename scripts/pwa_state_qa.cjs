/* Targeted state-label and explicit-link checks on the isolated no-provider server. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const baseURL=process.env.DEMO_URL||'http://127.0.0.1:8001';
const output=path.resolve(process.env.QA_OUTPUT||'data/pwa-qa-final');
let browser;
(async()=>{
  await fs.mkdir(output,{recursive:true});
  browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--use-file-for-fake-audio-capture='+path.resolve('fixtures/voice/note-1.wav')]});
  const context=await browser.newContext({baseURL,viewport:{width:390,height:844},permissions:['microphone']});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(baseURL+'/#journal');
  await page.waitForFunction(()=>typeof state!=='undefined'&&state);
  const before=(await(await context.request.get('/api/status')).json()).drafts.map(draft=>draft.digest);
  await page.locator('#record-note').click();
  await page.locator('#record-live').waitFor({state:'visible'});
  await page.waitForTimeout(1200);
  await page.locator('#stop-recording').click();
  await page.locator('#record-save').waitFor({state:'visible'});
  const title='Transcript label check '+Date.now();
  await page.locator('#record-note-title').fill(title);
  await page.locator('#save-recording').click();
  await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Add a transcript'));
  const entries=(await(await context.request.get('/api/journal')).json()).entries;
  const note=entries.find(entry=>entry.title===title);
  assert.equal(note.transcript_pending,true);
  await page.locator(`[data-journal-note="${note.id}"]`).click();
  await page.locator('#note-edit-text').fill('Synthetic note. I paused beside the green gate.');
  await page.locator('#save-transcript').click();
  await page.waitForFunction(()=>document.querySelector('#note-transcript').textContent.includes('green gate'));
  assert.equal(await page.locator('#connection').isVisible(),false);
  const updated=(await(await context.request.get('/api/journal')).json()).entries.find(entry=>entry.id===note.id);
  assert.equal(updated.transcript_pending,false);
  assert.equal(updated.transcription_mode,'manual transcript');
  await page.screenshot({path:path.join(output,'manual-transcript-current-label.png'),fullPage:true});
  await page.locator('#link-task').selectOption('claim');
  await page.locator('#link-note').click();
  await page.waitForFunction(()=>document.querySelector('#note-linked').textContent.includes('claim'));
  await page.locator('[data-close="note-dialog"]').click();
  await page.locator('.bottom-nav [data-view="tasks"]').click();
  const source=page.locator(`#screen-tasks [data-journal-note="${note.id}"]`);
  await source.waitFor();
  assert.match(await page.locator('#screen-tasks .linked-notes').first().innerText(),/Linked notes for your review/);
  await source.evaluate(element=>element.scrollIntoView({block:'center'}));
  await page.screenshot({path:path.join(output,'task-linked-journal-source.png')});
  await source.click();
  assert.match(await page.locator('#note-transcript').innerText(),/green gate/);
  const after=(await(await context.request.get('/api/status')).json()).drafts.map(draft=>draft.digest);
  assert.deepEqual(after,before);
  await page.locator('[data-close="note-dialog"]').click();
  await page.locator('.bottom-nav [data-view="home"]').click();
  assert.equal(await page.locator('#connection').isVisible(),false);
  const mock=await browser.newContext({baseURL,viewport:{width:390,height:844}});
  const generated=await mock.newPage();
  await generated.route('**/api/companion',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({saved:{id:'synthetic-generated-label-check',prompt:'A calm generated companion',style:'minimal',mode:'openai-generated',image_url:'/assets/companion-minimal.png'},previews:[],styles:['soft','playful','minimal']})}));
  await generated.goto(baseURL+'/#companion');
  await generated.waitForFunction(()=>typeof companion!=='undefined'&&companion?.saved?.mode==='openai-generated');
  assert.equal(await generated.locator('#companion-method').innerText(),'Generated companion');
  assert.equal(await generated.locator('#companion-saved').isVisible(),true);
  assert.match(await generated.locator('#companion-saved').innerText(),/generated companion is saved/);
  await generated.reload({waitUntil:'domcontentloaded'});
  await generated.waitForFunction(()=>typeof companion!=='undefined'&&companion?.saved?.mode==='openai-generated');
  assert.equal(await generated.locator('#companion-method').innerText(),'Generated companion');
  assert.match(await generated.locator('#companion-saved').innerText(),/generated companion is saved/);
  await generated.locator('#companion-saved').evaluate(element=>element.scrollIntoView({block:'center'}));
  await generated.screenshot({path:path.join(output,'persisted-generated-label.png')});
  const result={ok:true,persistedGeneratedCompanion:{modeLabel:'Generated companion',savedBadgeVisibleAfterReload:true,test:'Mocked persisted companion GET response only'},manualTranscript:{actualAudioUpload:true,wasPending:true,transcriptPendingAfterPatch:updated.transcript_pending,mode:updated.transcription_mode,staleBannerCleared:true,navigationKeepsBannerClear:true},linkedSource:{visibleFromTasks:true,opensSavedJournalSource:true,draftDigestsUnchanged:true},browserErrors:errors};
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(output,'state-label-check-results.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(async error=>{console.error(error);if(browser)await browser.close().catch(()=>{});process.exitCode=1;});
